### 5. Почему Index Only Scan работает?

```sql
-- Индекс содержит: (person_id, menu_id) для строк WHERE order_date='2022-01-01'
CREATE UNIQUE INDEX idx ON person_order (person_id, menu_id) 
WHERE order_date = '2022-01-01';

-- Запрос выбирает ТОЛЬКО menu_id
SELECT menu_id
FROM person_order
WHERE order_date = '2022-01-01' AND person_id = 2;
```

**Проверка:**
- ✅ `WHERE order_date = '2022-01-01'` → совпадает с условием индекса
- ✅ `WHERE person_id = 2` → person_id есть в индексе
- ✅ `SELECT menu_id` → menu_id есть в индексе

**Результат:**
```
PostgreSQL думает:
"WHERE order_date='2022-01-01' → у меня есть индекс для этой даты!"
"WHERE person_id=2 → найду в индексе"
"SELECT menu_id → menu_id есть в индексе"
"Всё есть в индексе → Index Only Scan!" ✅
```

---

### 6. Что если WHERE в запросе НЕ совпадает с индексом?

```sql
-- Индекс только для order_date='2022-01-01'
CREATE UNIQUE INDEX idx ON person_order (person_id, menu_id) 
WHERE order_date = '2022-01-01';

-- Запрос для ДРУГОЙ даты
SELECT menu_id
FROM person_order
WHERE order_date = '2022-01-02' AND person_id = 2;
```

**PostgreSQL думает:**
```
"WHERE order_date='2022-01-02'"
"У меня индекс только для '2022-01-01'"
"Индекс НЕ подходит!"
"Использую Sequential Scan" ❌
```

**Вывод:** Частичный индекс работает ТОЛЬКО если условие запроса **совпадает** с условием индекса!

