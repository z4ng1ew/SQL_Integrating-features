## Дополнительные объяснения для защиты

### 1. Что такое ЧАСТИЧНЫЙ индекс (Partial Index)?

**Partial Index** = индекс, который индексирует **НЕ ВСЕ строки**, а только те, что соответствуют условию

**Обычный индекс:**
```sql
CREATE INDEX idx ON person_order (person_id, menu_id);
-- Индексирует ВСЕ строки таблицы
```

**Частичный индекс:**
```sql
CREATE INDEX idx ON person_order (person_id, menu_id) 
WHERE order_date = '2022-01-01';
-- Индексирует ТОЛЬКО строки с order_date='2022-01-01'
-- Остальные строки НЕ попадают в индекс!
```

---

### Аналогия - картотека

**Обычная картотека (обычный индекс):**
```
Папки со ВСЕМИ документами компании:
├── 2020 год (все документы)
├── 2021 год (все документы)
├── 2022 год (все документы)
└── 2023 год (все документы)
```

**Специальная картотека (частичный индекс):**
```
Папка ТОЛЬКО с документами от 2022-01-01:
└── 2022-01-01 (только документы этой даты!)

Остальные документы НЕ попадают в эту папку!
```

