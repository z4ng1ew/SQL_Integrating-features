DROP INDEX IF EXISTS idx_person_order_order_date;
CREATE UNIQUE INDEX idx_person_order_order_date 
    ON person_order (person_id, menu_id) 
    WHERE order_date = '2022-01-01';

SET enable_seqscan = OFF;

EXPLAIN ANALYSE
SELECT menu_id
FROM person_order
WHERE order_date = '2022-01-01' 
  AND person_id = 2;


















-- Удаляем частичный уникальный индекс idx_person_order_order_date, если он существует
DROP INDEX IF EXISTS idx_person_order_order_date;

-- Создаём ЧАСТИЧНЫЙ УНИКАЛЬНЫЙ (partial unique) индекс на таблице person_order
-- UNIQUE - гарантирует уникальность комбинации (person_id, menu_id)
-- НО ТОЛЬКО для строк, где order_date = '2022-01-01' (условие WHERE в индексе!)
-- 
-- Что это означает:
-- 1. Индекс содержит ТОЛЬКО заказы от 2022-01-01 (остальные даты не индексируются)
-- 2. Уникальность проверяется ТОЛЬКО среди заказов от 2022-01-01
-- 3. Один человек не может заказать одну и ту же пиццу дважды в один день (2022-01-01)
-- 4. НО тот же человек МОЖЕТ заказать ту же пиццу в другой день (например, 2022-01-02)
--
-- Пример:
-- ✅ Разрешено: person_id=2, menu_id=5, order_date='2022-01-01'
-- ❌ Запрещено: person_id=2, menu_id=5, order_date='2022-01-01' (дубликат!)
-- ✅ Разрешено: person_id=2, menu_id=5, order_date='2022-01-02' (другая дата!)
--
-- WHERE order_date = '2022-01-01' - это НЕ условие запроса, это условие ИНДЕКСА!
-- Индекс "фильтрует" таблицу и индексирует только строки с order_date='2022-01-01'
CREATE UNIQUE INDEX idx_person_order_order_date 
    ON person_order (person_id, menu_id) 
    WHERE order_date = '2022-01-01';

-- Отключаем последовательное сканирование таблицы
-- Принудительно заставляет PostgreSQL использовать частичный индекс
-- Необходимо для демонстрации Index Only Scan
SET enable_seqscan = OFF;

-- EXPLAIN ANALYSE показывает план выполнения и доказывает использование Index Only Scan
-- Ожидается: "Index Only Scan using idx_person_order_order_date on person_order"
-- Index Only Scan сработает, т.к. SELECT запрашивает только menu_id, который ЕСТЬ в индексе
EXPLAIN ANALYSE
-- SELECT menu_id - выбираем ТОЛЬКО menu_id (один столбец)
-- menu_id входит в индекс (person_id, menu_id) → возможен Index Only Scan
-- Не запрашиваем столбцы id и order_date, которых НЕТ в индексе
SELECT menu_id
FROM person_order
-- КРИТИЧЕСКИ ВАЖНО: условие WHERE СОВПАДАЕТ с условием индекса!
-- order_date = '2022-01-01' - совпадает с WHERE в определении индекса → индекс применяется
-- person_id = 2 - первый столбец индекса → быстрый поиск через индекс
-- 
-- PostgreSQL понимает:
-- 1. WHERE order_date = '2022-01-01' → "Эй, у меня есть индекс ТОЛЬКО для этой даты!"
-- 2. WHERE person_id = 2 → "Могу быстро найти в индексе по person_id"
-- 3. SELECT menu_id → "menu_id есть в индексе → Index Only Scan!"
WHERE order_date = '2022-01-01' 
  AND person_id = 2;
