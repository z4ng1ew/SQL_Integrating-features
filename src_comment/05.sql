## Итог для защиты

**Вопрос:** Что такое частичный индекс?

**Ответ:**
1. Индекс, который индексирует **не все строки**, а только те, что удовлетворяют условию WHERE
2. В нашем случае: индексируются только заказы от 2022-01-01
3. Экономит место (маленький индекс) и обеспечивает специфичную уникальность

**Вопрос:** Зачем нужен UNIQUE в частичном индексе?

**Ответ:**
1. Гарантирует: один человек не может заказать одну пиццу дважды **в конкретный день** (2022-01-01)
2. Но **может** заказать ту же пиццу в другие дни
3. Без частичного индекса пришлось бы запрещать повторные заказы навсегда

**Вопрос:** Почему Index Only Scan работает?

**Ответ:**
1. WHERE в запросе совпадает с WHERE в индексе (order_date='2022-01-01')
2. SELECT запрашивает только menu_id, который есть в индексе
3. Все данные есть в индексе → таблицу не читаем → Index Only Scan