### 2. Зачем нужен частичный индекс?

**Преимущество 1: Экономия места**

```
Таблица person_order: 1 000 000 строк
Строки с order_date='2022-01-01': 1000 строк

Обычный индекс:
- Размер: индексирует 1 000 000 строк
- Занимает: ~50 MB

Частичный индекс:
- Размер: индексирует 1000 строк
- Занимает: ~0.05 MB (в 1000 раз меньше!)
```

**Преимущество 2: Специфичная уникальность**

Бизнес-правило: "Человек не может заказать одну пиццу дважды **в один день**"

```sql
-- Обычный UNIQUE - слишком строго
CREATE UNIQUE INDEX idx ON person_order (person_id, menu_id);
-- Запрещает: person_id=2, menu_id=5 во ВСЕЙ таблице
-- Человек НЕ может заказать пиццу 5 НИКОГДА больше! ❌

-- Частичный UNIQUE - правильно
CREATE UNIQUE INDEX idx ON person_order (person_id, menu_id) 
WHERE order_date = '2022-01-01';
-- Запрещает: person_id=2, menu_id=5 ТОЛЬКО 2022-01-01
-- Человек МОЖЕТ заказать пиццу 5 в другие дни! ✅
```

---

### 3. Как работает частичный индекс?

**Таблица person_order:**
```
id | person_id | menu_id | order_date
---|-----------|---------|------------
1  | 2         | 5       | 2022-01-01  ← попадёт в индекс
2  | 2         | 7       | 2022-01-01  ← попадёт в индекс
3  | 2         | 5       | 2022-01-02  ← НЕ попадёт (другая дата!)
4  | 3         | 5       | 2022-01-01  ← попадёт в индекс
5  | 2         | 5       | 2022-01-03  ← НЕ попадёт (другая дата!)
```

**Частичный индекс WHERE order_date = '2022-01-01':**
```
person_id | menu_id | → указатель
----------|---------|------------
2         | 5       | → строка 1  ✅
2         | 7       | → строка 2  ✅
3         | 5       | → строка 4  ✅

Строки 3 и 5 НЕ попали в индекс!
```

