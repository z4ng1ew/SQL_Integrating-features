### 4. Почему UNIQUE работает только для 2022-01-01?

```sql
-- Попытка 1: Вставить заказ
INSERT INTO person_order VALUES (1, 2, 5, '2022-01-01');
-- person_id=2, menu_id=5, order_date='2022-01-01'
-- ✅ ОК! Первая вставка

-- Попытка 2: Вставить ДУБЛИКАТ в ТОТ ЖЕ день
INSERT INTO person_order VALUES (6, 2, 5, '2022-01-01');
-- person_id=2, menu_id=5, order_date='2022-01-01'
-- ❌ ОШИБКА! Дубликат (person_id=2, menu_id=5) в индексе для 2022-01-01!

-- Попытка 3: Вставить в ДРУГОЙ день
INSERT INTO person_order VALUES (7, 2, 5, '2022-01-02');
-- person_id=2, menu_id=5, order_date='2022-01-02'
-- ✅ ОК! Другая дата → индекс НЕ проверяет эту строку!
```

**Почему разрешено?**
```
Индекс проверяет уникальность ТОЛЬКО среди строк с order_date='2022-01-01'
Строка с order_date='2022-01-02' НЕ попадает в индекс
→ Уникальность для неё НЕ проверяется
→ Разрешено! ✅
```

