## Почему индексы могут НЕ использоваться напрямую?

### Причина: PostgreSQL умный и выбирает оптимальный план

PostgreSQL имеет **оптимизатор запросов** (query planner/optimizer), который **автоматически решает**, использовать индекс или нет.

### Основные случаи, когда индекс НЕ используется:

---

#### 1. **Таблица слишком маленькая** (наш случай!)

```
Аналогия из жизни:
Нужно найти книгу в небольшой стопке из 10 книг

Вариант А (без индекса): Просто смотришь все 10 книг подряд (10 секунд)
Вариант Б (с индексом): Идёшь к каталогу → ищешь в каталоге → 
                         возвращаешься к полке → берёшь книгу (15 секунд)

Вывод: БЕЗ индекса быстрее!
```

**В нашей учебной базе:**
- Таблица `menu` содержит всего ~19 строк
- Таблица `pizzeria` содержит ~6 строк
- PostgreSQL считает: "Проще прочитать все 19 строк подряд (Sequential Scan), чем использовать индекс"

---

#### 2. **График из задания объясняет это:**

```
При малом количестве строк (слева на графике):
🔴 Sequential Scan (без индекса) - БЫСТРЕЕ
🟢 Index Scan (с индексом) - МЕДЛЕННЕЕ

При большом количестве строк (справа):
🔴 Sequential Scan - МЕДЛЕННЕЕ  
🟢 Index Scan - БЫСТРЕЕ
```

---

### Что нужно сделать, чтобы задействовать индексы?

#### Решение: `SET enable_seqscan = OFF;`

```sql
SET enable_seqscan = OFF;
```

**Что это делает:**
- Отключает возможность использования Sequential Scan
- **Принудительно заставляет** PostgreSQL использовать индексы
- Нужно **только для демонстрации** работы индексов в учебных целях

---

### Аналогия для понимания

```
Начальник (PostgreSQL оптимизатор):
- Видит задачу: "Найти 1 книгу среди 10"
- Решает: "Быстрее без каталога" → Sequential Scan

Ты говоришь (SET enable_seqscan = OFF):
- "Запрещаю смотреть книги подряд!"
- Начальник: "Ладно, использую каталог" → Index Scan

Результат: Индекс используется, но работа выполняется медленнее!
(В учебных целях это нормально - мы демонстрируем работу индекса)
```

