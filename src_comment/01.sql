## Итог для защиты:

**Вопрос:** Почему индексы могут не использоваться?

**Ответ:** 
1. PostgreSQL автоматически выбирает оптимальный план выполнения
2. При **малом количестве строк** Sequential Scan быстрее Index Scan из-за накладных расходов на чтение индекса
3. В нашей учебной базе ~19 строк → PostgreSQL выберет Sequential Scan
4. `SET enable_seqscan = OFF` принудительно отключает Sequential Scan для демонстрации работы индекса
5. В реальной работе эту команду **не используют** - PostgreSQL сам выбирает лучший план

**Вывод:** Индекс создан правильно, просто PostgreSQL считает его невыгодным для маленькой таблицы. Мы принудительно включаем его для проверки.