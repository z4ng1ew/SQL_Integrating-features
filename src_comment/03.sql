## Пример из C (для закрепления)

```c
struct index_entry {
    int person_id;
    int menu_id;
    char order_date[11];
};

// Индекс отсортирован!
struct index_entry index[] = {
    {1, 5,  "2022-01-01"},
    {1, 10, "2022-01-02"},
    {1, 19, "2022-01-03"},
    {2, 3,  "2022-01-01"},
    {2, 19, "2022-01-05"},
    {8, 19, "2022-01-05"},
    {8, 19, "2022-01-06"},
};

// ✅ Быстрый поиск: person_id = 8
// Бинарный поиск по первому полю - работает!
int left = 0, right = 6, mid;
while (left <= right) {
    mid = (left + right) / 2;
    if (index[mid].person_id == 8) {
        // Нашли! (~3 сравнения)
    }
}

// ❌ Медленный поиск: menu_id = 19
// Нужно проверить ВСЕ элементы массива!
for (int i = 0; i < 7; i++) {
    if (index[i].menu_id == 19) {
        // menu_id=19 разбросано по массиву:
        // index[2], index[4], index[5], index[6]
    }
}
// Бинарный поиск НЕ работает, т.к. массив НЕ отсортирован по menu_id!
```

