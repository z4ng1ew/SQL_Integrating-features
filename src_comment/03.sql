## Визуализация: как работает индекс

```
Индекс (person_id, menu_id, order_date):

          ┌─── Сортировка уровень 1: person_id
          │
    ┌─────┴─────┐
    │ person=1  │  person=2  │  person=8
    │           │            │
    └───┬───┬───┴───┬────┬───┴───┬───┬
        │   │       │    │       │   │
      ┌─┴─┐ │     ┌─┴─┐  │     ┌─┴─┐ │
      │ 5 │ │     │ 3 │  │     │19 │ │  ← Сортировка уровень 2: menu_id
      └───┘ │     └───┘  │     └───┘ │
          ┌─┴─┐        ┌─┴─┐       ┌─┴─┐
          │10 │        │19 │       │19 │
          └───┘        └───┘       └───┘
            │            │           │
         (даты)       (даты)      (даты)  ← Сортировка уровень 3: order_date
```

**Можно быстро спуститься:**
- ✅ `person_id = 8` → прыгаем в ветку "person=8"
- ✅ `person_id = 8 AND menu_id = 19` → прыгаем в "person=8" → потом в "menu=19"

**Нельзя быстро найти:**
- ❌ `menu_id = 19` → нужно проверить ВСЕ ветки person_id (разбросано!)
- ❌ `order_date = ...` → нужно проверить ВСЕ листья (разбросано!)

