## Итог простыми словами

**Многоколоночный индекс = лестница**

```
person_id (первая ступенька)
    ↓
  menu_id (вторая ступенька)
    ↓
  order_date (третья ступенька)
```

**Можно:**
- ✅ Спуститься на 1-ю ступеньку (`WHERE person_id = ...`)
- ✅ Спуститься на 1-ю, потом на 2-ю (`WHERE person_id = ... AND menu_id = ...`)
- ✅ Спуститься на все три (`WHERE person_id = ... AND menu_id = ... AND order_date = ...`)

**Нельзя:**
- ❌ Перепрыгнуть на 2-ю ступеньку, минуя 1-ю (`WHERE menu_id = ...`)
- ❌ Перепрыгнуть на 3-ю ступеньку (`WHERE order_date = ...`)

**Правило:** Всегда начинай с **первого столбца** индекса!

