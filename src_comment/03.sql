## В базе данных: индекс (person_id, menu_id, order_date)

### Как хранится индекс (отсортировано!)

```
person_id | menu_id | order_date
----------|---------|------------
1         | 5       | 2022-01-01   ← person_id=1, menu_id=5
1         | 10      | 2022-01-02   ← person_id=1, menu_id=10
1         | 19      | 2022-01-03   ← person_id=1, menu_id=19
2         | 3       | 2022-01-01   ← person_id=2, menu_id=3
2         | 19      | 2022-01-05   ← person_id=2, menu_id=19
8         | 19      | 2022-01-05   ← person_id=8, menu_id=19
8         | 19      | 2022-01-06   ← person_id=8, menu_id=19
```

**Сортировка:**
1. СНАЧАЛА по `person_id` (1, 1, 1, 2, 2, 8, 8)
2. Внутри каждого `person_id` - по `menu_id`
3. Внутри каждого `menu_id` - по `order_date`

---

### Почему работает: WHERE person_id = 8

```sql
WHERE person_id = 8
```

**PostgreSQL думает:**
```
"Индекс отсортирован по person_id!"
"Могу использовать бинарный поиск!"

Шаг 1: Смотрю середину индекса → person_id=2
       8 > 2 → ищу в правой половине
       
Шаг 2: Смотрю середину правой части → person_id=8
       Нашёл! ✅
```

Результат: **~3 шага** вместо просмотра всех строк

---

### Почему работает: WHERE person_id = 8 AND menu_id = 19

```sql
WHERE person_id = 8 AND menu_id = 19
```

**PostgreSQL думает:**
```
"Индекс отсортирован: сначала по person_id, потом по menu_id!"

Шаг 1: Бинарный поиск по person_id=8 → нашёл диапазон:
       person_id=8, menu_id=5
       person_id=8, menu_id=10
       person_id=8, menu_id=19 ← вот оно!
       person_id=8, menu_id=19
       
Шаг 2: Внутри person_id=8 ищу menu_id=19 (тоже отсортировано!)
       Нашёл! ✅
```

Результат: **~4 шага**

---

### Почему НЕ работает: WHERE menu_id = 19

```sql
WHERE menu_id = 19
```

**PostgreSQL думает:**
```
"Ищу menu_id=19..."
"Индекс отсортирован по person_id, а НЕ по menu_id!"

Смотрю индекс:
person_id=1, menu_id=5     ← menu_id=19? Нет
person_id=1, menu_id=10    ← menu_id=19? Нет
person_id=1, menu_id=19    ← menu_id=19? ДА! ✅
person_id=2, menu_id=3     ← menu_id=19? Нет
person_id=2, menu_id=19    ← menu_id=19? ДА! ✅
person_id=8, menu_id=19    ← menu_id=19? ДА! ✅
person_id=8, menu_id=19    ← menu_id=19? ДА! ✅

НЕ могу использовать бинарный поиск!
menu_id=19 разбросано по ВСЕМУ индексу!
Нужно просмотреть ВСЕ строки! ❌
```

Результат: **просмотр всех строк** (Sequential Scan) = индекс бесполезен!

---

### Почему НЕ работает: WHERE order_date = '2022-01-05'

```sql
WHERE order_date = '2022-01-05'
```

**PostgreSQL думает:**
```
"Ищу order_date='2022-01-05'..."
"Индекс отсортирован: person_id → menu_id → order_date"
"order_date - это ТРЕТИЙ уровень сортировки!"

Смотрю индекс:
person_id=1, menu_id=5,  order_date=2022-01-01  ← 2022-01-05? Нет
person_id=1, menu_id=10, order_date=2022-01-02  ← 2022-01-05? Нет
person_id=2, menu_id=3,  order_date=2022-01-01  ← 2022-01-05? Нет
