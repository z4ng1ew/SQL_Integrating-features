## Решение: создать отдельный индекс!

Если нужен поиск по `menu_id`:

```sql
-- Дополнительный индекс для поиска по menu_id
CREATE INDEX idx_menu_id ON person_order (menu_id);

-- Теперь работает быстро:
SELECT * FROM person_order WHERE menu_id = 19; ✅
```

Если нужен поиск по `order_date`:

```sql
-- Дополнительный индекс для поиска по дате
CREATE INDEX idx_order_date ON person_order (order_date);

-- Теперь работает быстро:
SELECT * FROM person_order WHERE order_date = '2022-01-05'; ✅
```

**Итого:** можно иметь несколько индексов на одной таблице для разных сценариев поиска!

