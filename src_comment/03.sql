person_id=8, menu_id=19, order_date=2022-01-05  ← 2022-01-05? ДА! ✅
person_id=8, menu_id=19, order_date=2022-01-06  ← 2022-01-05? Нет

Даты разбросаны по всему индексу!
Нужно просмотреть ВСЕ строки! ❌
```

